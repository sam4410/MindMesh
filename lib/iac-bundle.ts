import { strToU8, zipSync } from "fflate";

import type { CloudProvider } from "@/lib/cloud-services";
import { toSlug } from "@/lib/slug";

// Prisma's IacFormat (spec 66).
export const IAC_FORMATS = ["TERRAFORM", "BICEP"] as const;
export type IacFormat = (typeof IAC_FORMATS)[number];

export const IAC_FORMAT_LABELS: Record<IacFormat, string> = { TERRAFORM: "Terraform", BICEP: "Bicep" };

// AWS and GCP get Terraform; Azure also gets Bicep, its own language. Other providers get nothing.
const PROVIDER_FORMATS: Record<CloudProvider, readonly IacFormat[]> = {
  aws: ["TERRAFORM"],
  azure: ["TERRAFORM", "BICEP"],
  gcp: ["TERRAFORM"],
};

export function allowedIacFormats(provider: string | null | undefined): readonly IacFormat[] {
  return provider && Object.hasOwn(PROVIDER_FORMATS, provider) ? PROVIDER_FORMATS[provider as CloudProvider] : [];
}

// Why a project's provider can't generate this format, or null when it can.
export function iacFormatError(provider: string | null | undefined, format: IacFormat): string | null {
  const formats = allowedIacFormats(provider);
  if (formats.length === 0) return "Choose a cloud provider (AWS, Azure or Google Cloud) to generate infrastructure code";
  return formats.includes(format) ? null : `${IAC_FORMAT_LABELS[format]} is only available for Azure projects`;
}

// Generated bundles live in private Vercel Blob under one folder per project; IacBundle holds the metadata.
export function iacBlobFolder(projectId: string) {
  return `iac/${projectId}/`;
}

export function iacBlobPath(projectId: string, bundleId: string) {
  return `${iacBlobFolder(projectId)}${bundleId}.zip`;
}

// The name a bundle downloads under (spec 67), e.g. "chat-app-terraform-2026-11-27.zip".
export function iacFilename(projectName: string, format: IacFormat, createdAt: Date) {
  return `${toSlug(projectName) || "project"}-${format.toLowerCase()}-${createdAt.toISOString().slice(0, 10)}.zip`;
}

export type IacFile = { path: string; content: string };

export const IAC_MAX_FILES = 40;
export const IAC_MAX_BYTES = 200 * 1024;
const IAC_EXTENSIONS = [".tf", ".tfvars.example", ".bicep", ".json", ".md"];
const MAX_PATH_LENGTH = 200;
// Relative and "/"-separated; each segment starts with a letter, digit, "_" or "-", which rules out
// "..", "." and hidden files. No leading "/", backslashes, drive letters or spaces.
const SAFE_PATH = /^[A-Za-z0-9_-][A-Za-z0-9._-]*(\/[A-Za-z0-9_-][A-Za-z0-9._-]*)*$/;

// Checks the model's files before they're zipped: why they can't be, or null when they're fine.
export function iacFilesError(files: readonly IacFile[]): string | null {
  if (files.length === 0) return "The generated code has no files";
  if (files.length > IAC_MAX_FILES) {
    return `The generated code has ${files.length} files; the limit is ${IAC_MAX_FILES}`;
  }
  const seen = new Set<string>();
  let bytes = 0;
  for (const { path, content } of files) {
    if (path.length > MAX_PATH_LENGTH || !SAFE_PATH.test(path)) {
      return `The generated code has an unsafe file path: ${JSON.stringify(path.slice(0, 80))}`;
    }
    if (!IAC_EXTENSIONS.some((extension) => path.endsWith(extension))) {
      return `The generated code has a file type that isn't allowed: ${path}`;
    }
    // Case-insensitive, since the zip may be unpacked on Windows or macOS.
    const key = path.toLowerCase();
    if (seen.has(key)) return `The generated code has ${path} more than once`;
    seen.add(key);
    bytes += new TextEncoder().encode(content).length;
  }
  if (bytes > IAC_MAX_BYTES) {
    return `The generated code is ${Math.ceil(bytes / 1024)} KB; the limit is ${IAC_MAX_BYTES / 1024} KB`;
  }
  return null;
}

const REVIEW_STEPS: Record<IacFormat, string[]> = {
  TERRAFORM: [
    "1. Read every file and replace the placeholder values (in `<angle brackets>`).",
    "2. `terraform init`",
    "3. `terraform plan` (with `-var-file` for your environment) and check what it would create.",
    "4. `terraform apply` only once the plan is what you expect.",
  ],
  BICEP: [
    "1. Read every file and replace the placeholder values (in `<angle brackets>`).",
    "2. `az deployment group what-if --resource-group <group> --template-file main.bicep` and check what it would create.",
    "3. `az deployment group create --resource-group <group> --template-file main.bicep` only once that is what you expect.",
  ],
};

// The model is asked for a README.md; when it leaves one out, this one keeps the bundle usable.
export function withReadme(files: IacFile[], format: IacFormat, notes: readonly string[]): IacFile[] {
  if (files.some((file) => file.path.toLowerCase() === "readme.md")) return files;
  const content = [
    `# Infrastructure code (${IAC_FORMAT_LABELS[format]})`,
    "",
    "Generated by MindMesh from the project's design, for review only. MindMesh never applies it to your cloud.",
    "",
    "## Decisions to confirm and notes",
    "",
    ...(notes.length ? notes.map((note) => `- ${note}`) : ["- None given."]),
    "",
    "## Review, plan and apply",
    "",
    ...REVIEW_STEPS[format],
    "",
  ].join("\n");
  return [...files, { path: "README.md", content }];
}

// One zip with the files at their paths; call after iacFilesError.
export function zipIacFiles(files: readonly IacFile[]): Uint8Array {
  return zipSync(Object.fromEntries(files.map((file) => [file.path, strToU8(file.content)])));
}
